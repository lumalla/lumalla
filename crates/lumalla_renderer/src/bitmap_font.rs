fn glyph_index(ch: char) -> Option<usize> {
    match ch {
        'A'..='Z' => Some((ch as u8 - b'A') as usize),
        'a'..='z' => Some(26 + (ch as u8 - b'a') as usize),
        '0'..='9' => Some(52 + (ch as u8 - b'0') as usize),
        _ => None,
    }
}

/// Pixel size of a rendered label (always `len * CELL` even for blank cells).
pub fn label_size(text: &str) -> (u32, u32) {
    let width = (text.chars().count() as u32).saturating_mul(CELL_WIDTH as u32);
    (width.max(1), CELL_HEIGHT as u32)
}

/// Rasterize `text` into premultiplied BGRA8 pixels.
pub fn rasterize_label(text: &str, color: ColorRgba) -> (Vec<u8>, u32, u32) {
    let (width, height) = label_size(text);
    let mut pixels = vec![0u8; (width * height * 4) as usize];
    let premul = color.premultiplied_f32();
    let b = (premul[2] * 255.0).round() as u8;
    let g = (premul[1] * 255.0).round() as u8;
    let r = (premul[0] * 255.0).round() as u8;
    let a = (premul[3] * 255.0).round() as u8;

    for (col, ch) in text.chars().enumerate() {
        let Some(index) = glyph_index(ch) else {
            continue;
        };
        let glyph = &GLYPHS[index];
        for row in 0..GLYPH_SIZE {
            let bits = glyph[row as usize];
            for bit in 0..GLYPH_SIZE {
                if bits & (0x80 >> bit) == 0 {
                    continue;
                }
                let base_x = col as u32 * CELL_WIDTH as u32 + bit * SCALE;
                let base_y = row * SCALE;
                for dy in 0..SCALE {
                    for dx in 0..SCALE {
                        let x = base_x + dx;
                        let y = base_y + dy;
                        if x >= width || y >= height {
                            continue;
                        }
                        let i = ((y * width + x) * 4) as usize;
                        pixels[i] = b;
                        pixels[i + 1] = g;
                        pixels[i + 2] = r;
                        pixels[i + 3] = a;
                    }
                }
            }
        }
    }
    (pixels, width, height)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn blank_for_unsupported() {
        let (pixels, w, h) = rasterize_label("A B", ColorRgba::WHITE);
        assert_eq!((w, h), (72, 24));
        // Middle cell (space) should be fully transparent.
        let cell_bytes = (CELL_WIDTH as usize) * 4;
        let mid = cell_bytes;
        assert!(pixels[mid..mid + cell_bytes].iter().all(|&p| p == 0));
    }
}
